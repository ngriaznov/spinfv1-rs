fn eval(ins: Instruction, acc_in: i32) -> i32 {
    let mut fv1 = vm(&[
        Instruction::ldax(reg::ADCL),
        ins,
        Instruction::Wrax {
            reg: reg::DACL,
            c: 0,
        },
    ]);
    fv1.process_raw(acc_in, 0).0
}

#[test]
fn log_matches_pinned_values() {
    for &(c, d, acc, expected) in LOG_CASES {
        let got = eval(Instruction::Log { c, d }, acc);
        assert_eq!(got, expected, "LOG c={c} d={d} acc={acc}");
    }
}

#[test]
fn exp_matches_pinned_values() {
    for &(c, d, acc, expected) in EXP_CASES {
        let got = eval(Instruction::Exp { c, d }, acc);
        assert_eq!(got, expected, "EXP c={c} d={d} acc={acc}");
    }
}
