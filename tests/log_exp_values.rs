//! Exact-value regression for `LOG` and `EXP`.
//!
//! Rather than modeling the silicon's internal approximation curve, the
//! emulator's transcendental instructions are pinned to exact raw
//! outputs at a spread of accumulator values and coefficient/offset
//! combinations covering both domains: zero and near-zero inputs (LOG
//! saturates at the -16.0 domain floor), powers of two (exact log2
//! results), full scale, negative inputs (LOG takes |ACC|, EXP
//! saturates at 1.0 for ACC >= 0), and non-trivial C/D scaling. The
//! values were cross-validated against an independent FV-1
//! implementation (agreement within 1 LSB of its float pipeline at
//! every point) and are locked here bit-for-bit.

